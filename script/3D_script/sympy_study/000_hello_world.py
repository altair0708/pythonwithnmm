from sympy import *
import pickle

x_s = symbols('x0:4')
y_s = symbols('y0:4')
z_s = symbols('z0:4')

e, v = symbols('e v')

a = Matrix([[1, x_s[0], y_s[0], z_s[0]],
            [1, x_s[1], y_s[1], z_s[1]],
            [1, x_s[2], y_s[2], z_s[2]],
            [1, x_s[3], y_s[3], z_s[3]]])


f = (a**(-1)).T

B = Matrix([[f[0, 1],       0,       0, f[1, 1],       0,       0, f[2, 1],       0,       0, f[3, 1],       0,       0],
            [      0, f[0, 2],       0,       0, f[1, 2],       0,       0, f[2, 2],       0,       0, f[3, 2],       0],
            [      0,       0, f[0, 3],       0,       0, f[1, 3],       0,       0, f[2, 3],       0,       0, f[3, 3]],
            [f[0, 2], f[0, 1],       0, f[1, 2], f[1, 1],       0, f[2, 2], f[2, 1],       0, f[3, 2], f[3, 1],       0],
            [f[0, 3],       0, f[0, 1], f[1, 3],       0, f[1, 1], f[2, 3],       0, f[2, 1], f[3, 3],       0, f[3, 1]],
            [      0, f[0, 3], f[0, 2],       0, f[1, 3], f[1, 2],       0, f[2, 3], f[2, 2],       0, f[3, 3], f[3, 2]]])

E = Matrix([[1 - v,     v,     v,           0,           0,           0],
            [    v, 1 - v,     v,           0,           0,           0],
            [    v,     v, 1 - v,           0,           0,           0],
            [    0,     0,     0, (1 - 2*v)/2,           0,           0],
            [    0,     0,     0,           0, (1 - 2*v)/2,           0],
            [    0,     0,     0,           0,           0, (1 - 2*v)/2]])

result = B.T * E * B
print(result)

with open('stiff_matrix.bin', 'wb') as f:
    pickle.dump(result, f)
